function safeGet(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
}

function detectLocale() {
    const saved = safeGet(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
    // Existing private builds were Ukrainian; preserve their UI on upgrade.
    if (safeGet(i18nKeys.provider) !== null || safeGet(i18nKeys.prompt) !== null) return 'uk';
    try {
        const locale = require('uxp').host.uiLocale || '';
        if (String(locale).toLowerCase().startsWith('uk')) return 'uk';
    } catch (e) {}
    return 'en';
}

let locale = detectLocale();

function t(key, vars = {}) {
    const template = STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (_, name) =>
        Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`);
}

function applyDocument(root) {
    const scope = root || (typeof document !== 'undefined' ? document : null);
    if (!scope || !scope.querySelectorAll) return;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    for (const [attribute, dataName] of [['placeholder', 'i18nPlaceholder'], ['title', 'i18nTitle']]) {
        scope.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}]`).forEach(el => {
            el.setAttribute(attribute, t(el.dataset[dataName]));
        });
    }
    const select = scope.getElementById?.('language-select');
    if (select) select.value = locale;
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = locale;
}

function setLocale(next) {
    if (!SUPPORTED.includes(next) || next === locale) return;
    locale = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (e) {}
    applyDocument();
    if (typeof document !== 'undefined' && typeof Event !== 'undefined') {
        document.dispatchEvent(new Event('exactfill:localechange'));
    }
}

function getLocale() { return locale; }
function dateLocale() { return locale === 'uk' ? 'uk-UA' : 'en-US'; }

const api = { t, setLocale, getLocale, dateLocale, applyDocument, STRINGS, STORAGE_KEY };
if (typeof window !== 'undefined') window.exactFillI18n = api;
if (typeof module !== 'undefined') module.exports = api;

if (typeof document !== 'undefined') {
    document.addEventListener('DOMContentLoaded', () => applyDocument());
}
